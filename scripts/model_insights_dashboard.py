best_f1 = metrics_df.loc[best_idx, "F1_Score"]
best_mae = metrics_df.loc[best_idx, "MAE_kWh"]
best_rmse = metrics_df.loc[best_idx, "RMSE_kWh"]

k1, k2, k3, k4 = st.columns(4)
with k1:
    st.metric("🏆 Best Model (F1)", best_model)
with k2:
    st.metric("🎯 Best F1-Score", f"{best_f1:.4f}")
