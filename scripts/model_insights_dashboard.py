# ============================================================
# RESOLVE PATHS (works from project root or scripts/ folder)
# ============================================================

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent
DATA_DIR = PROJECT_ROOT / "Data" / "Processed"


# ============================================================
# DATA LOADING
# ============================================================

@st.cache_data
def load_metrics():
    """Load the performance comparison table."""
    path = DATA_DIR / "all_model_performance_metrics.csv"
    if not path.exists():
        return None
    return pd.read_csv(path)


# ============================================================
# HERO HEADER
