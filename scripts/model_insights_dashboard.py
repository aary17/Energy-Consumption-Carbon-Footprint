    st.markdown('<div class="section-header">🎯 Classification Metrics (Macro-Averaged)</div>', unsafe_allow_html=True)
    st.caption("Derived from Low / Medium / High energy categories. One-vs-rest, macro-averaged.")

    cls_cols = [
        "Accuracy", "Recall_Sensitivity", "Specificity", "Precision",
        "NPV", "FPR", "FDR", "FNR", "F1_Score",
    ]
    cls_long = metrics_df.melt(
        id_vars="Model",
        value_vars=cls_cols,
        var_name="Metric",
        value_name="Value",
    )
    cls_long["Metric"] = cls_long["Metric"].replace({
        "Recall_Sensitivity": "Recall",
        "F1_Score": "F1-Score",
    })

    fig_cls = px.bar(
        cls_long,
        x="Metric",
        y="Value",
        color="Model",
        barmode="group",
        text=cls_long["Value"].apply(lambda v: f"{v:.3f}"),
        color_discrete_sequence=["#059669", "#0ea5e9", "#f59e0b", "#ef4444"],
    )
    fig_cls.update_traces(textposition="outside", textfont_size=10)
    fig_cls.update_layout(
        height=480,
        margin=dict(l=20, r=20, t=30, b=30),
        yaxis=dict(range=[0, 1.12]),
        legend=dict(orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
    )
    st.plotly_chart(fig_cls, use_container_width=True)
